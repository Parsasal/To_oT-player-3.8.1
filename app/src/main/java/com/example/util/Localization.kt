/**
 * Translates session/lane names appropriately between Persian and English/other languages.
 */
fun getLocalizedSessionName(name: String, isPersianRtl: Boolean): String {
    val trimmed = name.trim()
    return when {
        trimmed.equals("ریمیکس", ignoreCase = true) || trimmed.equals("Remix", ignoreCase = true) -> if (isPersianRtl) "ریمیکس" else "Remix"
        trimmed.equals("منتخب", ignoreCase = true) -> if (isPersianRtl) "منتخب" else "Selected"
        trimmed.equals("Selected", ignoreCase = true) -> if (isPersianRtl) "منتخب" else "Selected"
        trimmed.equals("Favorites", ignoreCase = true) || trimmed.equals("Favorite", ignoreCase = true) -> if (isPersianRtl) "علاقه‌مندی‌ها" else "Favorites"
        trimmed.equals("Podcast & Voice", ignoreCase = true) -> if (isPersianRtl) "پادکست و گفتگو" else "Podcast & Voice"
        trimmed.equals("Workout", ignoreCase = true) -> if (isPersianRtl) "ورزش و تمرین" else "Workout"
        trimmed.equals("Audiobooks", ignoreCase = true) -> if (isPersianRtl) "کتاب‌های صوتی" else "Audiobooks"
        trimmed.equals("Night Chill", ignoreCase = true) -> if (isPersianRtl) "آرامش شبانه" else "Night Chill"
        trimmed.startsWith("Lane ", ignoreCase = true) && isPersianRtl -> trimmed.replace("Lane ", "لاین ", ignoreCase = true)
        trimmed.startsWith("لاین ", ignoreCase = true) && !isPersianRtl -> trimmed.replace("لاین ", "Lane ", ignoreCase = true)
        else -> name
    }
}
