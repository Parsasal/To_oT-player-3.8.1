/**
 * 6 Supported Languages in TO_OT Player
 */
enum class AppLanguage(
    val code: String,
    val nativeName: String,
    val englishName: String,
    val flag: String,
    val isRtl: Boolean
) {
    FA("fa", "فارسی", "Persian", "🇮🇷", true),
    EN("en", "English", "English", "🇺🇸", false),
    ES("es", "Español", "Spanish", "🇪🇸", false),
    ZH("zh", "简体中文", "Chinese", "🇨🇳", false),
    HI("hi", "हिन्दी", "Hindi", "🇮🇳", false),
    PT("pt", "Português", "Portuguese", "🇧🇷", false);

    val layoutDirection: LayoutDirection
        get() = if (isRtl) LayoutDirection.Rtl else LayoutDirection.Ltr

    companion object {
        fun fromCode(code: String?): AppLanguage {
            return entries.find { it.code.equals(code, ignoreCase = true) } ?: EN
        }
    }
}

